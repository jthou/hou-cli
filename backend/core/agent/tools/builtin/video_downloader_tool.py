def _load_cookies_from_file(cookies_file: str) -> Optional[str]:
    """从文件加载 cookies
    
    Args:
        cookies_file: Cookies 文件路径（Netscape 格式或 JSON 格式）
    
    Returns:
        Cookies 文件路径（如果有效），否则返回 None
    """
    try:
        cookies_path = Path(cookies_file)
        if not cookies_path.exists():
            logger.warning(f"Cookies 文件不存在: {cookies_file}")
            return None
        
        # 检查文件格式
        with open(cookies_path, 'r', encoding='utf-8') as f:
            first_line = f.readline().strip()
            # Netscape 格式通常以 "# Netscape HTTP Cookie File" 开头
            # JSON 格式以 "[" 或 "{" 开头
            if first_line.startswith('#') or first_line.startswith('[') or first_line.startswith('{'):
                logger.info(f"成功加载 cookies 文件: {cookies_file}")
                return str(cookies_path)
            else:
                logger.warning(f"Cookies 文件格式可能不正确: {cookies_file}")
                return None
    except Exception as e:
        logger.error(f"加载 cookies 文件失败: {e}")
        return None


def _extract_cookies_from_browser(browser: str, domain: str = 'bilibili.com') -> Optional[str]:
    """从浏览器提取 cookies
    
    Args:
        browser: 浏览器名称（'chrome', 'firefox', 'safari', 'edge'）
        domain: 域名（默认 'bilibili.com'）
    
    Returns:
        临时 cookies 文件路径（如果成功），否则返回 None
    """
    try:
        import browser_cookie3  # type: ignore
    except ImportError:
        logger.warning("browser_cookie3 未安装，无法从浏览器提取 cookies。请运行: pip install browser-cookie3")
        return None
    except Exception as e:
        logger.error(f"导入 browser_cookie3 失败: {e}")
        return None
    
    try:
        import tempfile
        
        # 根据浏览器类型选择提取方法
        if browser.lower() == 'chrome':
            cookies = browser_cookie3.chrome(domain_name=domain)
        elif browser.lower() == 'firefox':
            cookies = browser_cookie3.firefox(domain_name=domain)
        elif browser.lower() == 'safari':
            cookies = browser_cookie3.safari(domain_name=domain)
        elif browser.lower() == 'edge':
            cookies = browser_cookie3.edge(domain_name=domain)
        else:
            logger.warning(f"不支持的浏览器: {browser}")
            return None
        
        if not cookies:
            logger.warning(f"从 {browser} 中未找到 {domain} 的 cookies")
            return None
        
        # 创建临时文件（Netscape 格式）
        temp_file = tempfile.NamedTemporaryFile(mode='w', suffix='.txt', delete=False)
        temp_file.write("# Netscape HTTP Cookie File\n")
        temp_file.write("# This file was generated by video_downloader_tool\n\n")
        
        for cookie in cookies:
            # Netscape 格式: domain, flag, path, secure, expiration, name, value
            domain_str = cookie.domain
            flag = 'TRUE' if domain_str.startswith('.') else 'FALSE'
            path = cookie.path or '/'
            secure = 'TRUE' if cookie.secure else 'FALSE'
            expiration = str(int(cookie.expires)) if cookie.expires else '0'
            name = cookie.name
            value = cookie.value
            
            temp_file.write(f"{domain_str}\t{flag}\t{path}\t{secure}\t{expiration}\t{name}\t{value}\n")
        
        temp_file.close()
        logger.info(f"成功从 {browser} 提取 cookies，保存到: {temp_file.name}")
        return temp_file.name
        
    except Exception as e:
        logger.error(f"从浏览器提取 cookies 失败: {e}")
        return None


def _pick_format_from_available(formats: List[Dict[str, Any]], quality: str) -> Optional[str]:
    """从可用格式列表中按质量偏好选择 format 选择器。返回 None 时由 yt-dlp 默认选择。"""
    if not formats:
        return None
    max_height = None
    if quality in ('1080p', '720p', '480p', '360p', '240p'):
        max_height = {'1080p': 1080, '720p': 720, '480p': 480, '360p': 360, '240p': 240}.get(quality)
    # 分离视频轨和音频轨
    videos = [f for f in formats if f.get('vcodec') and f.get('vcodec') != 'none']
    audios = [f for f in formats if f.get('acodec') and f.get('acodec') != 'none']
    if max_height:
        videos = [f for f in videos if (f.get('height') or 0) <= max_height]
    if not videos and not audios:
        return None
    # 按分辨率/码率排序，取最佳
    def vid_key(f):
        return (f.get('height') or 0, f.get('tbr') or 0)
    def aud_key(f):
        return (f.get('abr') or 0, f.get('tbr') or 0)
    videos.sort(key=vid_key, reverse=True)
    audios.sort(key=aud_key, reverse=True)
    best_v = videos[0] if videos else None
    best_a = audios[0] if audios else None
    if best_v and best_a and best_v.get('format_id') != best_a.get('format_id'):
        return f"{best_v['format_id']}+{best_a['format_id']}"
    if best_v:
        return best_v['format_id']
    if best_a:
        return best_a['format_id']
    return None


def _log_ytdlp_equiv_cmd(ydl_opts: Dict[str, Any], url: str) -> None:
    """输出等效 yt-dlp CLI 命令，便于在终端复现对比"""
    equiv_parts = ["yt-dlp"]
    if ydl_opts.get('outtmpl'):
        equiv_parts.append(f"-o {repr(ydl_opts['outtmpl'])}")
    if ydl_opts.get('format'):
        equiv_parts.append(f"-f {repr(ydl_opts['format'])}")
    if ydl_opts.get('format_sort'):
        sort_str = ",".join(ydl_opts['format_sort'])
        equiv_parts.append(f"-S {repr(sort_str)}")
    if ydl_opts.get('cookiefile'):
        equiv_parts.append(f"--cookies {repr(ydl_opts['cookiefile'])}")
    if ydl_opts.get('extractor_args', {}).get('youtube'):
        yt = ydl_opts['extractor_args']['youtube']
        if yt.get('player_client'):
            pc = ",".join(yt['player_client']) if isinstance(yt['player_client'], (list, tuple)) else yt['player_client']
            equiv_parts.append(f"--extractor-args {repr('youtube:player_client=' + pc)}")
    equiv_parts.append(repr(url))
    logger.info("等效 CLI 命令（可复制到终端对比）: %s", " ".join(equiv_parts))



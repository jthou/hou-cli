"""
视觉 OCR 提示词（网页截图 / PDF 页图共用）。

说明：
- 与「微信读书」应用并无 API 级对接；对齐的是本仓库内 **web-reader** 在 source=weread 时
  使用的 **同一套提示词规则**（通用公式/表格 + 可选章节标题增补）。
- 调用方：web_reader /ocr、pdf_vision_extract 等应统一通过 build_vision_ocr_prompt，避免分叉。
"""

from __future__ import annotations

from typing import Optional

OCR_PROMPT = """请识别图片中的所有文字，按原文顺序逐行输出。如果是书籍或文章页面，请完整提取正文内容，保留段落结构。

**数学公式**：若图片中有数学公式（如 LaTeX、算式、符号等），请用以下格式包裹：
- 行内公式：用单个美元符号包裹，如 $E=mc^2$
- 独立成行的公式：用双美元符号包裹，如 $$\\int_0^1 x\\,dx = \\frac{1}{2}$$

**矩阵与多行排版**：若出现矩阵、向量竖排或多行公式，请用 LaTeX 环境写出结构，不要用一行随意拼接：
- 方括号矩阵优先用 `bmatrix`（圆括号可用 `pmatrix`），独立成行时用双美元包裹整块，例如：
  $$\\begin{bmatrix} a_{11} & a_{12} \\\\ a_{21} & a_{22} \\end{bmatrix}$$
- 矩阵内**每一行**之间必须用 `\\\\` 换行；列与列之间用 `&` 分隔。
- 与原文一致的省略号请写成 `\\cdots`、`\\ldots` 等对应 LaTeX 命令，不要随意改成文字「…」混在公式里（若整段是公式环境内则保持命令形式）。

**表格**：若图片中有表格（含三线表、有线框表），请输出为 **Markdown 表格**（管道符 `|`），不要用纯空格对齐冒充表格：
- 第一行为表头，第二行为分隔行，仅含 `|---|` 这类短横线与竖线，列数与表头一致；自第三行起为数据行。
- 示例：
  | 列A | 列B |
  | --- | --- |
  | 单元格 | 单元格 |
- 单元格内换行可写成 `<br>` 或合并为一行用顿号分隔（择一保持全表一致）；空单元格用单个空格或 `-` 占位。
- 若存在跨行/跨列合并且难以用 Markdown 表达，在表前或表后用一行简短说明「某格合并」即可，其余仍按规整网格输出，不要省略整表。

**页眉、页脚与页码（PDF/纸书页图，必须省略）**：出现在**页顶/底边、页角、装订侧窄条**的内容（单独或成行的页码如 `12`、`Page 12`、`第 12 页`，书名/刊名/机构眉题、脚注区重复提示等），**一律不要写入输出**——既不要标成 `#` 标题，也不要当普通正文粘贴。**只输出版心内的主体正文**（含正文中的脚注编号引用可保留，但页脚长说明若属版式上的「整页脚栏」可省略）。**正文第一个真正的标题**从版心主体起算。

**分页隔断**：你输出的是**当前这一张图**的内容；不要在结果里自行添加「第 n 页」标题行或 `---` 类人工分页线。多页 PDF 合并时，**程序会在页与页之间插入隔断标记**（你无需模仿或重复）；单页识别请勿臆造分页符。

只输出识别到的文字，不要添加任何解释或评论。"""

# 仅当 source=weread 时追加：与通用规则叠加；多层级 `4.1.4　标题` 式编号才映射 ATX，避免页码被当成「单段编号」误标为一级标题。
OCR_WEREAD_HEADING_SUPPLEMENT = """

**章节编号与 Markdown 标题（微信读书等电子书章节页）**：
在已遵守上文「页眉页脚与页码须省略、且不作标题」的前提下，仅当某行在版式上是**版心内的章节/小节标题**（字号明显大于正文或独立成块），且行首编号为**多段十进制整数用英文句点 `.` 连接**（**至少含一个 `.`**，例如 `4.1`、`4.1.4`、`12.3.1`）时，请将该行输出为 **Markdown ATX 标题**：
- `#` 的个数 = 编号中「`.` 分段」的个数：两段用 `##`，三段用 `###`，依此类推，**最多六级** `######`。
- 输出形式示例：`### 4.1.4 数据滤波`、`## 4.1 某某节`（编号与标题文字均保留）。
- **整行仅有阿拉伯数字**、或数字位于**页边/页角**、或符合上文明示的**页码形式**的，**一律不得**用本规则标为标题。
- **单独一段整数编号**（无 `.`，如 `4 绪论`）若确需标标题：仅当该行**明显在版心且为大标题**、且**不是**页码形态时，可用**一级** `#`；若无法区分页码与章号，**宁可普通行**也不要误标 `#`。
- **不要**把有序列表（如 `1.` 列举）或正文中的「3.14」「式 (2.3)」等改成标题。
"""


def build_vision_ocr_prompt(*, source: Optional[str] = None) -> str:
    """
    组装最终 OCR 文本提示。
    source: 传 weread（大小写不敏感）时追加章节标题规则，与 POST /api/web-reader/ocr 一致。
    """
    s = (source or "").strip().lower()
    if s == "weread":
        return OCR_PROMPT + OCR_WEREAD_HEADING_SUPPLEMENT
    return OCR_PROMPT
